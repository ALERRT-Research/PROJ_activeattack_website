# Builds the downloadable codebook PDF (data/aa_codebook_<version>.pdf) from
# the same rows as the Codebook page (R/codebook.R), in the fact sheet's
# design. R writes Typst to fact_sheet/aa_codebook.typ and compiles it with the
# Typst bundled in Quarto. Run locally after a data update; the PDF is
# committed (the CI site build does not run this).
#
#   Rscript R/codebook_pdf.R
#==============================================================================

