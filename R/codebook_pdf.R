# escape text for Typst content blocks
# (perl = TRUE: in TRE the \] inside the class ends it early and nothing is escaped)
ty <- function(x) gsub("([\\\\#$*_@<>\\[\\]`~=])", "\\\\\\1", x, perl = TRUE)
fmt_date <- function(d) gsub("  ", " ", format(d, "%B %e, %Y"))

#--rows----------------------------------------------------------------------------

values_cell <- function(r) {
  if (!is.na(r$values)) return(glue("[{ty(r$values)}]"))
  lv <- r$levels[[1]]
  items <- paste0("[", ty(lv$level), "], [", scales::comma(lv$n), "]", collapse = ",\n      ")
  glue("levels(\n      {items})")
}

missing_cell <- function(r) {
  if (r$n_missing == 0) return("text(fill: prevc)[none]")
  pct <- scales::number(r$pct_missing, accuracy = if (r$pct_missing < 1) 0.1 else 1)
  glue("[{scales::comma(r$n_missing)} #text(fill: muted)[({pct}\\%)]]")
}

var_cell <- function(r) {
  note <- if (is.na(r$note)) "" else glue("#linebreak() #text(size: 7.5pt, fill: muted)[{ty(r$note)}]")
  glue("[#raw(\"{r$variable}\") #linebreak() {ty(r$label)} {note}]")
}

group_block <- function(g, r) {
  body <- map_chr(seq_len(nrow(r)), function(i) {
    x <- r[i, ]
    paste(var_cell(x), glue("text(fill: muted)[{ty(x$type)}]"), values_cell(x), missing_cell(x), sep = ",\n    ")
  })
  glue("#cb-table([{ty(g)}], {nrow(r)}, (\n    {paste(body, collapse = ',\n    ')},\n  ))")
}

